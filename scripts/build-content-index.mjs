/**
 * Writes src/locales/contentIndex.generated.ts: for every tool, which text files hold its guide steps, questions and
 * article. A tool page then downloads only those files instead of the text of every tool (see src/locales/contentLoader.ts).
 *
 *   node scripts/build-content-index.mjs          writes the file (run by `pnpm run dev` and `pnpm run build`)
 *   node scripts/build-content-index.mjs --check  fails when the file on disk is out of date
 *
 * The list and the order of the text files come from src/locales/content.ts (baseContent, PACKS, DEPTH), which stays the single
 * place to add a pack. The merge rules the loader applies (src/locales/contentSplit.ts) are the same ones content.ts applies:
 * the last base or pack file that has a key wins, then each depth file adds its extra sections or questions.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = join(root, 'src', 'locales');
const outFile = join(localesDir, 'contentIndex.generated.ts');
const SECTIONS = ['guideSteps', 'pageGuides', 'toolArticles'];

const source = readFileSync(join(localesDir, 'content.ts'), 'utf8');
const files = new Map();
for (const match of source.matchAll(/^import (\w+) from '\.\/((?:packs|content|depth)\/[\w.-]+\.json)';$/gm)) files.set(match[1], match[2]);
const list = (name) => {
  const match = new RegExp(`const ${name}(?::[^=]+)? = \\[([^\\]]*)\\];`).exec(source);
  if (!match) throw new Error(`content.ts: could not find the ${name} list`);
  return match[1].split(',').map((item) => item.trim()).filter(Boolean);
};
if (!files.has('baseContent')) throw new Error('content.ts: baseContent import not found');
const textNames = ['baseContent', ...list('PACKS')];
const depthNames = list('DEPTH');
const fileOf = (name) => { const file = files.get(name); if (!file) throw new Error(`content.ts: no import found for ${name}`); return file; };

const entries = [...textNames.map((name) => ({ name, kind: 'text' })), ...depthNames.map((name) => ({ name, kind: 'depth' }))];
const seenFiles = new Set();
for (const entry of entries) {
  entry.file = fileOf(entry.name);
  if (seenFiles.has(entry.file)) throw new Error(`content.ts lists ${entry.file} twice`);
  seenFiles.add(entry.file);
  entry.data = JSON.parse(readFileSync(join(localesDir, entry.file), 'utf8'));
}

// Which files hold each key. A depth file is listed only for keys that some text file has, because that is the only time
// content.ts applies it.
const index = Object.fromEntries(SECTIONS.map((section) => [section, new Map()]));
entries.forEach((entry, position) => {
  if (entry.kind !== 'text') return;
  for (const section of SECTIONS) for (const key of Object.keys(entry.data[section] ?? {})) {
    const list = index[section].get(key) ?? [];
    list.push(position);
    index[section].set(key, list);
  }
});
entries.forEach((entry, position) => {
  if (entry.kind !== 'depth') return;
  for (const section of ['toolArticles', 'pageGuides']) for (const key of Object.keys(entry.data[section] ?? {})) {
    if (index[section].has(key)) index[section].get(key).push(position);
  }
});

const sortedObject = (map) => `{ ${[...map.keys()].sort().map((key) => `${JSON.stringify(key)}: [${map.get(key).join(', ')}]`).join(', ')} }`;
const output = `/* eslint-disable */
// Generated by scripts/build-content-index.mjs from src/locales/content.ts. Do not edit it by hand: run \`node scripts/build-content-index.mjs\`.
// \`pnpm run dev\` and \`pnpm run build\` run it for you.

export type Section = 'guideSteps' | 'pageGuides' | 'toolArticles';

/** Whether file number n is a text file (base or pack) or a depth file that adds to a text file's entries. */
export const SOURCE_KINDS: readonly ('text' | 'depth')[] = [${entries.map((entry) => `'${entry.kind}'`).join(', ')}];

/** One loader per file, in the order of content.ts. Each file becomes its own chunk. */
export const SOURCE_LOADERS: readonly (() => Promise<{ default: unknown }>)[] = [
${entries.map((entry) => `  () => import('./${entry.file}'),`).join('\n')}
];

/** For each section and key, the numbers of the files that hold it, in the order they are applied. */
export const CONTENT_INDEX: Record<Section, Record<string, readonly number[]>> = {
${SECTIONS.map((section) => `  ${section}: ${sortedObject(index[section])},`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== output) {
    console.error('src/locales/contentIndex.generated.ts is out of date. Run: node scripts/build-content-index.mjs');
    process.exit(1);
  }
  console.log('contentIndex.generated.ts is up to date.');
} else {
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== output) writeFileSync(outFile, output);
  console.log(`contentIndex.generated.ts: ${entries.length} files, ${SECTIONS.map((section) => `${index[section].size} ${section}`).join(', ')}`);
}
